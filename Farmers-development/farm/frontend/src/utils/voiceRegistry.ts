// ----------------------------------------------------------------------------
// Text Normalization: Safely strips punctuation without destroying Indic scripts
// ----------------------------------------------------------------------------
export function normalizeVoiceInput(input: string): string {
  if (!input) return '';
  return input
    .toLowerCase()
    .replace(/[.,/#!$%^&*;:{}=\-_`~()?"'।॥]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

// ----------------------------------------------------------------------------
// Voice Command Matching Engine
// ----------------------------------------------------------------------------
export interface MatchResult {
  route: string;
  commandId: string;
  label: string;
  confirmation: string;
  matchedAlias: string;
}

const COMMON_STOP_WORDS = new Set([
  'the', 'is', 'at', 'which', 'on', 'a', 'an', 'and', 'or', 'to', 'in', 'of', 'for', 'with', 
  'as', 'by', 'that', 'this', 'it', 'from', 'be', 'are', 'was', 'were', 'hai', 'ka', 'ki', 'ke', 'ko', 'me'
]);

function escapeRegExp(string: string): string {
  return string.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function matchesAlias(normalizedInput: string, normalizedAlias: string): boolean {
  if (!normalizedInput || !normalizedAlias) return false;
  if (COMMON_STOP_WORDS.has(normalizedInput)) return false;

  // 1. Exact match
  if (normalizedInput === normalizedAlias) return true;

  // 2. Word boundary match: input contains alias as a distinct word or phrase
  const escaped = escapeRegExp(normalizedAlias);
  const regex = new RegExp(`(^|\\s)${escaped}(\\s|$)`, 'i');
  if (regex.test(normalizedInput)) return true;

  // 3. Multi-word alias check: all significant words in alias are present in input
  const aliasWords = normalizedAlias.split(' ').filter(w => w.length > 2 && !COMMON_STOP_WORDS.has(w));
  if (aliasWords.length > 1 && aliasWords.every(w => normalizedInput.includes(w))) {
    return true;
  }

  return false;
}

export function matchVoiceCommand(
  rawTranscript: string,
  currentLanguage: SupportedLanguage = 'en'
): MatchResult | null {
  const normalized = normalizeVoiceInput(rawTranscript);
  if (!normalized) return null;
  if (COMMON_STOP_WORDS.has(normalized)) return null;

  // 1. Check in the current language first
  for (const cmd of ROUTE_COMMANDS) {
    const langAliases = cmd.aliases[currentLanguage] || [];
    for (const alias of langAliases) {
      const normAlias = normalizeVoiceInput(alias);
      if (matchesAlias(normalized, normAlias)) {
        return {
          route: cmd.route,
          commandId: cmd.id,
          label: cmd.labels[currentLanguage] || cmd.labels.en,
          confirmation: cmd.confirmations[currentLanguage] || cmd.confirmations.en,
          matchedAlias: alias,
        };
      }
    }
  }

  // 2. Fall back to English aliases (farmers frequently use English technical words e.g. "marketplace kholo")
  if (currentLanguage !== 'en') {
    for (const cmd of ROUTE_COMMANDS) {
      const enAliases = cmd.aliases.en || [];
      for (const alias of enAliases) {
        const normAlias = normalizeVoiceInput(alias);
        if (matchesAlias(normalized, normAlias)) {
          return {
            route: cmd.route,
            commandId: cmd.id,
            label: cmd.labels[currentLanguage] || cmd.labels.en,
            confirmation: cmd.confirmations[currentLanguage] || cmd.confirmations.en,
            matchedAlias: alias,
          };
        }
      }
    }
  }

  // 3. Fall back across all other languages
  for (const cmd of ROUTE_COMMANDS) {
    for (const [lang, aliases] of Object.entries(cmd.aliases)) {
      if (lang === currentLanguage || lang === 'en') continue;
      for (const alias of aliases) {
        const normAlias = normalizeVoiceInput(alias);
        if (matchesAlias(normalized, normAlias)) {
          return {
            route: cmd.route,
            commandId: cmd.id,
            label: cmd.labels[currentLanguage] || cmd.labels.en,
            confirmation: cmd.confirmations[currentLanguage] || cmd.confirmations.en,
            matchedAlias: alias,
          };
        }
      }
    }
  }

  return null;
}

